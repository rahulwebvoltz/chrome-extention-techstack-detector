// Builds the extension into dist/ in two passes:
//   1. popup + background service worker (ES modules, may share chunks)
//   2. content script as a single self-contained IIFE
//      (content scripts can't be ES modules, so they must not import chunks)
//
// Usage: node scripts/build.mjs [--watch] [--no-gpl-pack]
//
// --no-gpl-pack  leave out the optional GPL-3.0 Wappalyzer rules pack, so the
//                build contains only our own rules.
import { resolve } from "node:path";
import { existsSync, rmSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { build } from "vite";

const root = resolve(import.meta.dirname, "..");
const watch = process.argv.includes("--watch") ? {} : null;
const usePack = !process.argv.includes("--no-gpl-pack");
const runScript = (name) => execFileSync(process.execPath, [resolve(root, "scripts", name)], { stdio: "inherit" });

// Optional GPL rules pack → src/detector/packs/active.js
if (usePack) {
  if (!existsSync(resolve(root, "vendor/webappanalyzer/categories.json"))) {
    console.error("GPL pack data missing: run `npm run pack:fetch`, or build without it using --no-gpl-pack.");
    process.exit(1);
  }
  runScript("import-wappalyzer.mjs");
}
writeFileSync(
  resolve(root, "src/detector/packs/active.js"),
  [
    "// GENERATED by scripts/build.mjs — selects which optional rule packs are built in.",
    "// Default build: the GPL Wappalyzer pack. `npm run build -- --no-gpl-pack`: none.",
    usePack ? 'export { default } from "./wappalyzer.generated.js";' : "export default [];",
    ""
  ].join("\n")
);
console.log(usePack ? "rules: ours + GPL Wappalyzer pack" : "rules: ours only (no GPL pack)");

// Brand logos for the rules (src/components/techIcons.generated.js)
runScript("generate-tech-icons.mjs");

// Upstream per-technology icons (GPL pack builds only) → public/tech-icons/
if (usePack) runScript("copy-tech-icons.mjs");
else rmSync(resolve(root, "public/tech-icons"), { recursive: true, force: true });

// Empty dist/ once up front. Each pass then writes with emptyOutDir: false —
// otherwise a watch-mode rebuild of the popup would wipe content.js.
rmSync(resolve(root, "dist"), { recursive: true, force: true });

await build({
  root,
  configFile: resolve(root, "vite.config.js"),
  build: { watch, emptyOutDir: false }
});

await build({
  root,
  configFile: false,
  publicDir: false,
  build: {
    outDir: "dist",
    emptyOutDir: false,
    watch,
    lib: {
      entry: resolve(root, "src/content/content.js"),
      name: "TechStackContent",
      formats: ["iife"],
      fileName: () => "content.js"
    }
  }
});
