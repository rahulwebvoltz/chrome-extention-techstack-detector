// Generates src/components/techIcons.generated.js: brand logos (SVG paths)
// for every technology rule, from Simple Icons (CC0, https://simpleicons.org).
//
// Only the icons our rules use are written out, so the popup bundle doesn't
// carry all ~3,500 icons. Technologies without a Simple Icons logo fall back
// to a coloured letter tile in the UI. Runs automatically as part of build.
//
// To pick a specific icon for a rule, add `icon: "<simple-icons slug>"` to the
// rule, or an entry to ICON_OVERRIDES below.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import * as simpleIcons from "simple-icons";
import { titleToSlug } from "simple-icons/sdk";
import coreRules from "../src/detector/rules/index.js";
import packRules from "../src/detector/packs/active.js";

const rules = [...coreRules, ...packRules.filter((r) => !r.supplement)];

const OUT = resolve(import.meta.dirname, "../src/components/techIcons.generated.js");

// Rule name → Simple Icons slug, where the name doesn't map automatically.
const ICON_OVERRIDES = {
  "Amazon CloudFront": "amazonwebservices",
  "Apache HTTP Server": "apache",
  "ASP.NET": "dotnet",
  Java: "openjdk",
  "Meta Pixel": "meta",
  "Facebook SDK": "facebook",
  "X (Twitter) widgets": "x",
  "Elementor Pro": "elementor",
  "Elementor Header & Footer Builder": "elementor",
  "Hello Elementor": "elementor",
  "Cloudflare Browser Insights": "cloudflare",
  "Cloudflare Rocket Loader": "cloudflare",
  "Cloudflare Turnstile": "cloudflare",
  "Site Kit by Google": "google",
  "Google Publisher Tag": "googleads",
  "jQuery Migrate": "jquery",
  "jQuery UI": "jquery",
  SvelteKit: "svelte",
  SolidJS: "solid",
  "HubSpot CMS": "hubspot",
  "Plausible": "plausibleanalytics",
  "Semantic UI": "semanticuireact",
  Lottie: "lottiefiles",
  "Microsoft Clarity": "microsoft",
  "Microsoft IIS": "microsoft",
  "TikTok Pixel": "tiktok",
  "Rank Math SEO": "rankmath",
  "Yoast SEO": "yoast",
  "Salesforce Commerce Cloud": "salesforce",
  "Amazon S3": "amazons3",
  "Amazon Web Services": "amazonwebservices",
  "Google Cloud": "googlecloud",
  "GitHub Pages": "githubpages",
  "Font Awesome": "fontawesome",
  "Adobe Fonts": "adobefonts",
  "Bunny Fonts": "bunnydotnet",
  "Open Graph": "opengraph"
};

const bySlug = new Map(Object.values(simpleIcons).filter((i) => i?.slug).map((i) => [i.slug, i]));

const icons = {};
const missing = [];
for (const rule of rules) {
  const candidates = [rule.icon, ICON_OVERRIDES[rule.name], titleToSlug(rule.name)].filter(Boolean);
  const icon = candidates.map((slug) => bySlug.get(slug)).find(Boolean);
  if (icon) icons[rule.name] = { path: icon.path, hex: `#${icon.hex}` };
  else missing.push(rule.name);
}

writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-tech-icons.mjs — do not edit.\n` +
    `// Logos from Simple Icons (CC0 1.0), https://simpleicons.org\n` +
    `export default ${JSON.stringify(icons, null, 0).replace(/\},"/g, '},\n"')};\n`
);

console.log(`tech icons: ${Object.keys(icons).length}/${rules.length} technologies have a logo`);
if (process.argv.includes("--verbose")) console.log(`letter tiles: ${missing.join(", ")}`);
