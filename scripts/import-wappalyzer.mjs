// Converts vendor/webappanalyzer (GPL-3.0) into the optional rules pack
// src/detector/packs/wappalyzer.generated.js.
//
//   npm run pack:fetch    # download latest data into vendor/
//   npm run pack:import   # convert it (also runs on every build when the pack is enabled)
import { readFileSync, writeFileSync, existsSync, renameSync, statSync } from "node:fs";
import { resolve } from "node:path";
import coreRules from "../src/detector/rules/index.js";
import { convertAll } from "./lib/convertWappalyzer.mjs";

const VENDOR = resolve(import.meta.dirname, "../vendor/webappanalyzer");
const OUT = resolve(import.meta.dirname, "../src/detector/packs/wappalyzer.generated.js");

if (!existsSync(resolve(VENDOR, "categories.json"))) {
  console.error("vendor/webappanalyzer not found — run `npm run pack:fetch` first.");
  process.exit(1);
}

const read = (p) => JSON.parse(readFileSync(resolve(VENDOR, p), "utf8"));
const categories = read("categories.json");
const technologies = Object.assign({}, ...["_", ..."abcdefghijklmnopqrstuvwxyz"].map((c) => read(`technologies/${c}.json`)));
const source = readFileSync(resolve(VENDOR, "SOURCE.md"), "utf8").match(/Commit: (\w+)/)?.[1] ?? "unknown";

const { rules, stats } = convertAll(technologies, categories, coreRules.map((r) => r.name));

// Oversized upstream icons → their 64px PNG rendition (scripts/optimize-icons.mjs)
const MAX_ICON_BYTES = 50_000;
for (const rule of rules) {
  if (!rule.iconFile) continue;
  const original = resolve(VENDOR, "icons", rule.iconFile);
  const optimized = resolve(VENDOR, "icons-optimized", `${rule.iconFile}.png`);
  if (existsSync(original) && statSync(original).size > MAX_ICON_BYTES) {
    if (existsSync(optimized)) rule.iconFile = `optimized/${rule.iconFile}.png`;
    else delete rule.iconFile;
  }
}

// Write to a temp file and rename, so an interrupted import can never leave a
// truncated pack behind (which would break the next build).
const TMP = `${OUT}.tmp`;
writeFileSync(
  TMP,
  `// GENERATED by scripts/import-wappalyzer.mjs — do not edit.
// Fingerprints from https://github.com/enthec/webappanalyzer @ ${source.slice(0, 7)}
// Licensed GPL-3.0 (vendor/webappanalyzer/LICENSE). Optional: build without it
// using \`npm run build -- --no-gpl-pack\`.
export default JSON.parse(${JSON.stringify(JSON.stringify(rules))});
`
);
renameSync(TMP, OUT);

console.log(
  `GPL pack: ${stats.converted} technologies converted, ${stats.supplements ?? 0} of our rules supplemented ` +
    `(${stats.skippedCore} already covered by our rules, ${stats.skippedServerOnly} server-side only, ` +
    `${stats.invalidPatterns} invalid patterns dropped)`
);
